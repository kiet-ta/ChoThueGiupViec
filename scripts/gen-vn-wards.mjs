// Generates the post-merger Vietnamese ward data used by the worker work area (WORKERS-WARD-V2-01, #959).
//
//   node scripts/gen-vn-wards.mjs
//
// Source: https://provinces.open-api.vn/api/v2 (34 provinces/cities, wards/communes, no district level). Developer script only:
// the apps and the backend never call that API at run time. It writes two files, then you commit them:
//   Backend/Infrastructure/Modules/Workers/Data/vn-wards.json   (embedded in the backend, validates ward codes)
//   Mobile/lib/features/workers/models/vn_wards.dart            (the picker; searches the old names too)
// The old (pre-merger) ward names come from GET /w/{code}/to-legacies/ (one call per ward, a few minutes).
import fs from 'node:fs';
import path from 'node:path';

const API = 'https://provinces.open-api.vn/api/v2';
const root = path.resolve(import.meta.dirname, '..');
const jsonOut = path.join(root, 'Backend/Infrastructure/Modules/Workers/Data/vn-wards.json');
const dartOut = path.join(root, 'Mobile/lib/features/workers/models/vn_wards.dart');

async function get(url, tries = 5) {
  for (let i = 1; ; i++) {
    try {
      const res = await fetch(url);
      if (res.status === 404) return [];
      if (!res.ok) throw new Error(`${res.status} ${url}`);
      return await res.json();
    } catch (e) {
      if (i >= tries) throw e;
      await new Promise((r) => setTimeout(r, 500 * i));
    }
  }
}

const provinces = (await get(`${API}/p/`)).map((p) => ({ code: p.code, name: p.name }));
const wards = (await get(`${API}/w/`)).map((w) => ({ code: w.code, name: w.name, provinceCode: w.province_code, legacy: [] }));
console.log(`provinces ${provinces.length}, wards ${wards.length}`);

// Old names, 8 requests at a time.
let next = 0;
let done = 0;
await Promise.all(
  Array.from({ length: 8 }, async () => {
    while (next < wards.length) {
      const ward = wards[next++];
      const olds = await get(`${API}/w/${ward.code}/to-legacies/`);
      // Distinct, and not the same text as the new name.
      ward.legacy = [...new Set(olds.map((o) => o.name))].filter((n) => n !== ward.name);
      if (++done % 500 === 0) console.log(`legacy ${done}/${wards.length}`);
    }
  }),
);

if (provinces.length !== 34) throw new Error(`expected 34 provinces, got ${provinces.length}`);
if (new Set(wards.map((w) => w.code)).size !== wards.length) throw new Error('duplicate ward code');
const known = new Set(provinces.map((p) => p.code));
if (wards.some((w) => !known.has(w.provinceCode))) throw new Error('ward with an unknown province');

const generatedAt = new Date().toISOString().slice(0, 10);
fs.mkdirSync(path.dirname(jsonOut), { recursive: true });
fs.writeFileSync(jsonOut, JSON.stringify({ source: `${API} (downloaded ${generatedAt})`, provinces, wards }) + '\n');

const q = (s) => `'${s.replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('$', '\\$')}'`;
const dart = [
  '// GENERATED by scripts/gen-vn-wards.mjs: do not edit by hand.',
  `// Source: ${API} (downloaded ${generatedAt}).`,
  '// Vietnamese administrative units in force since 2025-07-01: provinces/cities and their wards, communes and special zones',
  '// (the district level no longer exists), with the pre-merger ward names so a worker can still search for them.',
  '',
  '/// A province or city.',
  'class VnProvince {',
  '  final int code;',
  '  final String name;',
  '',
  '  const VnProvince(this.code, this.name);',
  '}',
  '',
  '/// A ward, commune or special zone; [legacy] are the names of the wards that were merged into it.',
  'class VnWard {',
  '  final int code;',
  '  final String name;',
  '  final int provinceCode;',
  '  final List<String> legacy;',
  '',
  '  const VnWard(this.code, this.name, this.provinceCode, [this.legacy = const []]);',
  '}',
  '',
  'const List<VnProvince> vnProvinces = [',
  ...provinces.map((p) => `  VnProvince(${p.code}, ${q(p.name)}),`),
  '];',
  '',
  'const List<VnWard> vnWards = [',
  ...wards.map((w) => `  VnWard(${w.code}, ${q(w.name)}, ${w.provinceCode}${w.legacy.length ? `, [${w.legacy.map(q).join(', ')}]` : ''}),`),
  '];',
  '',
].join('\n');
fs.writeFileSync(dartOut, dart);
console.log(`wrote ${path.relative(root, jsonOut)} and ${path.relative(root, dartOut)}`);
